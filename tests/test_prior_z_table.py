"""v2 card prior: the per-card z table exported by the evaluated v5 model.

Frozen witnesses (name -> z, float32 from card_prior_z_table.npz) were
printed by tools-data/export_prior_v5_table.py right after the export
witness reproduced the stored FRA/DFT spearman (0.6648/0.6149). If a value
here changes, the asset was regenerated by a different model — investigate
before updating.
"""

import pytest

from src.advisor import deck_scorer as _ds


def test_table_asset_loads():
    _ds._load_prior_z_table()
    assert len(_ds._PRIOR_Z_TABLE) > 30000


def test_frozen_witnesses():
    _ds._load_prior_z_table()
    # FRA top cards by actual WR (17Lands): the model's strongest calls
    assert abs(_ds._PRIOR_Z_TABLE["ajani unrelenting"] - 2.3569) < 1e-3
    assert abs(_ds._PRIOR_Z_TABLE["uldaros theorix"] - 1.6112) < 1e-3
    assert abs(_ds._PRIOR_Z_TABLE["sublime epiphany"] - 0.7738) < 1e-3
    # a vanilla 2/2 for 2 sits below the set mean, not at an extreme
    assert -1.5 < _ds._PRIOR_Z_TABLE["grizzly bears"] < 0.0
    # split cards are stored under their full scryfall name
    assert abs(_ds._PRIOR_Z_TABLE["fire // ice"] - (-0.3320)) < 1e-3


def test_power_floor_witnesses():
    # v2: absolute structural floors lift out-of-distribution power cards
    # (forge v2 signals; calibrated on Jitte z=+5.44 TMT / Wurmcoil +3.96 BRO)
    _ds._load_prior_z_table()
    assert _ds._PRIOR_Z_TABLE["black lotus"] == 5.0
    assert _ds._PRIOR_Z_TABLE["sol ring"] == 4.0
    assert _ds._PRIOR_Z_TABLE["mox sapphire"] == 4.0
    assert _ds._PRIOR_Z_TABLE["ancestral recall"] == 4.5
    assert _ds._PRIOR_Z_TABLE["demonic tutor"] == 3.0
    # in-distribution cards keep the v5 statistical value (not the floor)
    assert abs(_ds._PRIOR_Z_TABLE["ajani unrelenting"] - 2.3569) < 1e-3


def test_feature_prior_z_uses_table():
    assert abs(_ds._feature_prior_z({"name": "Grizzly Bears"}) - (-0.715)) < 1e-3


def test_clamp_follows_manifest():
    # z=5.0 must survive the clamp (manifest widens to +-5.5 for floors)
    assert _ds._feature_prior_z({"name": "Black Lotus"}) == 5.0
    assert _ds._PRIOR_Z_CLAMPS == (-5.5, 5.5)
    # name normalization and curly apostrophes hit the same row
    direct = _ds._feature_prior_z({"name": "Aurelia's Vindicator"})
    curly = _ds._feature_prior_z({"name": "AURELIA’S VINDICATOR"})
    assert abs(direct - curly) < 1e-6


def test_face_name_lookup_hits_full_row():
    # single-face names resolve to the split card's row via the loader's
    # face index. ("Fire" is a colliding face of both "Start // Fire" and
    # "Fire // Ice" — first wins there, so use unambiguous faces here.)
    for face, full in (("Ice", "Fire // Ice"), ("Finality", "Find // Finality")):
        z_full = _ds._feature_prior_z({"name": full})
        z_face = _ds._feature_prior_z({"name": face})
        assert abs(z_face - z_full) < 1e-6, face


def test_unknown_card_falls_back_without_error():
    z = _ds._feature_prior_z({"name": "ZZZ Not A Real Card"})
    assert isinstance(z, float)
    assert -2.0 <= z <= 2.0


def test_card_wr_posteriors_carries_prior():
    # end-to-end: the table prior moves the shrinkage target off the raw
    # value. metrics=None -> set mean = the card's own All Decks gihwr and
    # sigma approx 4.0: target = 60 + 2.0*4 = 68; n=50 -> 68 + (60-68)*50/400
    card = {"name": "Ajani Unrelenting",
            "deck_colors": {"All Decks": {"gihwr": 60.0, "samples": 500},
                            "WR": {"gihwr": 58.0, "samples": 50}}}
    post = _ds.card_wr_posteriors(card, ["W", "R"])
    assert abs(post["prior_z"] - 2.3569) < 1e-3
    # global posterior uses the GLOBAL count (n=500): 69.43 + (60-69.43)*500/850
    assert post["shrunk_global"] == pytest.approx(69.43 - 9.43 * 500 / 850, abs=0.02)
    # arch posterior uses the pair count (n=50): 69.43 + (58-69.43)*50/400
    assert post["shrunk_arch"] == pytest.approx(69.43 - 11.43 * 50 / 400, abs=0.02)
